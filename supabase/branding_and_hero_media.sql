-- Energy KvA: identidad corporativa (store_settings) y medios del Hero (hero_slides)
-- Ejecutar en Supabase > SQL Editor. Es idempotente.

-- ===== store_settings =====
CREATE TABLE IF NOT EXISTS public.store_settings (
  id integer PRIMARY KEY DEFAULT 1
);
ALTER TABLE public.store_settings ADD COLUMN IF NOT EXISTS store_name text DEFAULT 'Energy KvA';
ALTER TABLE public.store_settings ADD COLUMN IF NOT EXISTS tagline text;
ALTER TABLE public.store_settings ADD COLUMN IF NOT EXISTS logo_url text;
ALTER TABLE public.store_settings ADD COLUMN IF NOT EXISTS footer_logo_url text;
ALTER TABLE public.store_settings ADD COLUMN IF NOT EXISTS logo_white text;
ALTER TABLE public.store_settings ADD COLUMN IF NOT EXISTS logo_dark text;

-- ===== hero_slides =====
CREATE TABLE IF NOT EXISTS public.hero_slides (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
);
ALTER TABLE public.hero_slides ADD COLUMN IF NOT EXISTS title text;
ALTER TABLE public.hero_slides ADD COLUMN IF NOT EXISTS subtitle text;
ALTER TABLE public.hero_slides ADD COLUMN IF NOT EXISTS button_text text;
ALTER TABLE public.hero_slides ADD COLUMN IF NOT EXISTS button_link text DEFAULT '/catalogo';
ALTER TABLE public.hero_slides ADD COLUMN IF NOT EXISTS media_url text;
ALTER TABLE public.hero_slides ADD COLUMN IF NOT EXISTS mobile_media_url text;
ALTER TABLE public.hero_slides ADD COLUMN IF NOT EXISTS sort_order integer DEFAULT 0;
ALTER TABLE public.hero_slides ADD COLUMN IF NOT EXISTS is_active boolean DEFAULT true;
ALTER TABLE public.hero_slides ADD COLUMN IF NOT EXISTS created_at timestamptz DEFAULT now();

-- Lectura pública (la tienda usa la anon key); las escrituras van por service role
ALTER TABLE public.store_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.hero_slides ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "public read store_settings" ON public.store_settings;
CREATE POLICY "public read store_settings" ON public.store_settings FOR SELECT USING (true);
DROP POLICY IF EXISTS "public read hero_slides" ON public.hero_slides;
CREATE POLICY "public read hero_slides" ON public.hero_slides FOR SELECT USING (true);
